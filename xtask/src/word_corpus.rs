/// A fixed-layout bordered table; with `header`, row 1 repeats on each page.
fn table(cols: &[u32], rows: usize, header: bool, seed: u32, fixed: bool) -> String {
    let total: u32 = cols.iter().sum();
    let layout = if fixed { r#"<w:tblLayout w:type="fixed"/>"# } else { "" };
    let mut t = format!(
        r#"<w:tbl><w:tblPr><w:tblW w:w="{total}" w:type="dxa"/>{BORDERS}{layout}<w:tblCellMar><w:left w:w="108" w:type="dxa"/><w:right w:w="108" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>"#
    );
    for c in cols {
        let _ = write!(t, r#"<w:gridCol w:w="{c}"/>"#);
    }
    t += "</w:tblGrid>";
    for row in 0..rows {
        let head = header && row == 0;
        t += "<w:tr>";
        if head {
            t += "<w:trPr><w:tblHeader/></w:trPr>";
        }
        for (k, c) in cols.iter().enumerate() {
            let content = if head {
                r("<w:b/>", &format!("Column {}", k + 1))
            } else {
                r("", &text(seed.wrapping_add((row * 7 + k) as u32), 2 + (row * 3 + k * 5) % 13))
            };
            let shade = if head { r#"<w:shd w:val="clear" w:color="auto" w:fill="D9E2F3"/>"# } else { "" };
            t += &cell(*c, r#"<w:spacing w:after="0"/>"#, &content, shade);
        }
        t += "</w:tr>";
    }
    t + "</w:tbl>"
}

