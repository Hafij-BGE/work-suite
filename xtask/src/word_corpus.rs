//! `cargo xtask word-corpus <outdir>`: writes the synthetic layout corpus, small DOCX files that
//! each exercise one area of Word's page layout (fonts, spacing, justification, styles, lists,
//! tabs, tables, pictures, breaks, pagination, headers and footers). The text, pictures and
//! styles are our own and generated here, so the files can be shared; the PDFs Word makes from
//! them are not committed (see `docs/word-fidelity.md`).
//!
//! Every document defines all of its styles, its page size and its compatibility mode, so Word's
//! own defaults (Normal template, theme fonts) can't change the result.

use std::fmt::Write as _;
use std::path::Path;

/// One corpus document.
struct Doc {
    name: &'static str,
    /// What the file tests, written to `MANIFEST.txt`.
    about: &'static str,
    /// `w:docDefaults` run properties.
    rpr: String,
    /// `w:docDefaults` paragraph properties.
    ppr: String,
    compat: u32,
    /// Extra `w:compat` switches (before the compatibility mode).
    compat_extra: &'static str,
    body: String,
    /// `w:sectPr` contents for the last section (page size, margins, header and footer refs).
    sect: String,
    header: Option<String>,
    footer: Option<String>,
    numbering: bool,
    images: Vec<Vec<u8>>,
}

impl Doc {
    fn new(name: &'static str, about: &'static str, font: &str, half_points: u32) -> Doc {
        Doc {
            name,
            about,
            rpr: format!(
                r#"<w:rFonts w:ascii="{font}" w:hAnsi="{font}" w:eastAsia="{font}" w:cs="{font}"/><w:sz w:val="{half_points}"/><w:szCs w:val="{half_points}"/><w:lang w:val="en-US"/>"#
            ),
            ppr: r#"<w:spacing w:after="160" w:line="259" w:lineRule="auto"/>"#.into(),
            compat: 15,
            compat_extra: "",
            body: String::new(),
            sect: LETTER.into(),
            header: None,
            footer: None,
            numbering: false,
            images: Vec::new(),
        }
    }
}

/// US Letter, 1 inch margins.
const LETTER: &str = r#"<w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720" w:gutter="0"/><w:cols w:space="720"/>"#;
/// A4, 2.5 cm / 2 cm margins.
const A4: &str = r#"<w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1417" w:right="1134" w:bottom="1134" w:left="1134" w:header="708" w:footer="708" w:gutter="0"/><w:cols w:space="708"/>"#;

pub fn run(args: &[&str]) -> Result<(), String> {
    let [out] = args else { return Err("usage: cargo xtask word-corpus <outdir>".into()) };
    let out = Path::new(out);
    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    let docs = corpus();
    let mut manifest = String::from("WordCraft synthetic layout corpus. Original text and pictures, generated by `cargo xtask word-corpus`.\n\n");
    for d in &docs {
        let bytes = docx(d)?;
        let path = out.join(format!("{}.docx", d.name));
        std::fs::write(&path, bytes).map_err(|e| format!("{}: {e}", path.display()))?;
        let _ = writeln!(manifest, "{}.docx\n    {}\n", d.name, d.about);
    }
    std::fs::write(out.join("MANIFEST.txt"), manifest).map_err(|e| e.to_string())?;
    println!("wrote {} documents to {}", docs.len(), out.display());
    Ok(())
}

