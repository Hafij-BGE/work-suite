/// Deterministic filler text: `n` words from the list, sentences capitalised and ended.
fn text(seed: u32, n: usize) -> String {
    let mut s = seed.wrapping_mul(2_654_435_761).wrapping_add(12_345);
    let mut out = String::new();
    let mut cap = true;
    for i in 0..n {
        s = s.wrapping_mul(1_103_515_245).wrapping_add(12_345);
        let w = WORDS[(s >> 8) as usize % WORDS.len()];
        if i > 0 {
            out.push(' ');
        }
        if cap {
            let mut c = w.chars();
            if let Some(f) = c.next() {
                out.extend(f.to_uppercase());
                out.push_str(c.as_str());
            }
        } else {
            out.push_str(w);
        }
        cap = false;
        let end = (s >> 20).is_multiple_of(11) || i + 1 == n;
        if end {
            out.push(if (s >> 4).is_multiple_of(7) { ',' } else { '.' });
            cap = !out.ends_with(',');
        }
    }
    if out.ends_with(',') {
        out.pop();
        out.push('.');
    }
    out
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

/// A run: `w:rPr` contents and text (spaces kept).
fn r(rpr: &str, t: &str) -> String {
    let rp = if rpr.is_empty() { String::new() } else { format!("<w:rPr>{rpr}</w:rPr>") };
    format!(r#"<w:r>{rp}<w:t xml:space="preserve">{}</w:t></w:r>"#, esc(t))
}

/// A paragraph: `w:pPr` contents and runs.
fn p(ppr: &str, runs: &str) -> String {
    let pp = if ppr.is_empty() { String::new() } else { format!("<w:pPr>{ppr}</w:pPr>") };
    format!("<w:p>{pp}{runs}</w:p>")
}

fn pt(ppr: &str, t: &str) -> String {
    p(ppr, &r("", t))
}

const BR: &str = "<w:r><w:br/></w:r>";
const PAGE_BREAK: &str = r#"<w:r><w:br w:type="page"/></w:r>"#;
const TAB: &str = "<w:r><w:tab/></w:r>";

fn heading(level: u32, t: &str) -> String {
    pt(&format!(r#"<w:pStyle w:val="Heading{level}"/>"#), t)
}

/// A PAGE / NUMPAGES field as runs.
fn field(instr: &str) -> String {
    format!(
        r#"<w:r><w:fldChar w:fldCharType="begin"/></w:r><w:r><w:instrText xml:space="preserve"> {instr} </w:instrText></w:r><w:r><w:fldChar w:fldCharType="separate"/></w:r><w:r><w:t>1</w:t></w:r><w:r><w:fldChar w:fldCharType="end"/></w:r>"#
    )
}

